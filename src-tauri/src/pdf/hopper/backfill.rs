    // ─── execute_backfill ───────────────────────────────────────────

    #[test]
    fn execute_backfill_moves_files_and_reports_outcomes() {
        let src = tempfile::tempdir().unwrap();
        let out = tempfile::tempdir().unwrap();
        seed_pdfs(src.path(), &["one.pdf", "two.pdf"]);

        let report = plan_backfill(src.path(), &base_watch(out.path()), &[]);
        assert_eq!(report.scanned, 2);
        let run = execute_backfill(&report);

        assert_eq!(run.applied, 2, "{:?}", run.per_file);
        assert_eq!(run.skipped, 0);
        assert_eq!(run.errored, 0);
        // Originals gone …
        assert!(!src.path().join("one.pdf").exists());
        assert!(!src.path().join("two.pdf").exists());
        // … and reachable in the destination.
        let out_files: Vec<_> = fs::read_dir(out.path())
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().to_string())
            .collect();
        assert_eq!(out_files.len(), 2);
    }

